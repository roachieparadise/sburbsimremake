package com.main.java.modelss;

public class Player {
    private String name;
    private String chumHandle;
    private String aspect;
    private String aspectColor;
    private String playerClass;
    private String color;
    private String specibus;
    private int grist;
    private int rungLevel;
    
    public Player() {}
    
    public String getName() { return name; }
    public void setName(String name) { this.name = name; }
    
    public String getChumHandle() { return chumHandle; }
    public void setChumHandle(String chumHandle) { this.chumHandle = chumHandle; }
    
    public String getAspect() { return aspect; }
    public void setAspect(String aspect) { this.aspect = aspect; }
    
    public String getAspectColor() { return aspectColor; }
    public void setAspectColor(String aspectColor) { this.aspectColor = aspectColor; }
    
    public String getPlayerClass() { return playerClass; }
    public void setPlayerClass(String playerClass) { this.playerClass = playerClass; }
    
    public String getColor() { return color; }
    public void setColor(String color) { this.color = color; }
    
    public String getStrife() { return specibus; }
    public void setStrife(String specibus) { this.specibus = specibus; }
    
    public int getGrist() { return grist; }
    public void setGrist(int grist) { this.grist = grist; }
    
    public int getRungLevel() { return rungLevel; }
    public void setRungLevel(int rungLevel) { this.rungLevel = rungLevel; }
}